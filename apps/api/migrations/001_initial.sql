CREATE TABLE sessions (
  id         TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE messages (
  seq        BIGINT NOT NULL,
  session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'summary')),
  content    TEXT NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY (session_id, seq)
);

CREATE TABLE tool_calls (
  seq         BIGINT NOT NULL,
  session_id  TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  input_json  TEXT NOT NULL,
  result_json TEXT NOT NULL,
  created_at  TEXT NOT NULL,
  PRIMARY KEY (session_id, seq)
);

-- Intentionally no FK to sessions: usage rows must survive transcript
-- retention/deletion so they continue to protect the daily cost budget.
CREATE TABLE usage (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id    TEXT NOT NULL,
  client_key    TEXT NOT NULL,
  input_tokens  INTEGER NOT NULL,
  output_tokens INTEGER NOT NULL,
  created_at    TEXT NOT NULL
);

CREATE INDEX idx_messages_session ON messages (session_id, seq);
CREATE INDEX idx_tool_calls_session ON tool_calls (session_id, seq);
CREATE INDEX idx_usage_day ON usage (created_at);
CREATE INDEX idx_usage_client_day ON usage (client_key, created_at);
